"""Write the viewer's colour maps (256 RGB entries each) as a C header
(viewer/amrviz_colormaps.h) from matplotlib:

    python3 tools/make_colormap_header.py > viewer/amrviz_colormaps.h

viridis and magma (van der Walt & Smith) are CC0; coolwarm is Moreland's
diverging map (free to use); gray is linear.
"""
import matplotlib

MAPS = [("viridis", 0), ("magma", 0), ("coolwarm", 1), ("gray", 0)]   # (name, diverging)

print("/* Generated by tools/make_colormap_header.py from matplotlib %s." % matplotlib.__version__)
print(" * viridis, magma: CC0 (S. van der Walt, N. Smith); coolwarm: K. Moreland. */")
print("#ifndef AMRVIZ_COLORMAPS_INCLUDED\n#define AMRVIZ_COLORMAPS_INCLUDED\n")
print("#define AMRVIZ_CMAP_COUNT %d\n#define AMRVIZ_CMAP_SIZE 256\n" % len(MAPS))
print("static const char *const amrviz_cmap_names[AMRVIZ_CMAP_COUNT] = { %s };"
      % ", ".join('"%s"' % n for n, _ in MAPS))
print("static const int amrviz_cmap_diverging[AMRVIZ_CMAP_COUNT] = { %s };\n"
      % ", ".join(str(d) for _, d in MAPS))
print("/* one row of 256 RGB triplets per map */")
print("static const unsigned char amrviz_cmaps[AMRVIZ_CMAP_COUNT * AMRVIZ_CMAP_SIZE * 3] = {")
for name, _ in MAPS:
    cm = matplotlib.colormaps[name]
    print("    /* %s */" % name)
    vals = []
    for k in range(256):
        r, g, b, _a = cm(k / 255.0)
        vals += [round(255 * r), round(255 * g), round(255 * b)]
    for i in range(0, len(vals), 24):
        print("    " + ",".join(str(v) for v in vals[i:i + 24]) + ",")
print("};\n\n#endif")
