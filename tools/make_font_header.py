"""Render printable ASCII (32..126) of a monospace TTF font into bitmap
atlases and write them as a C header for the viewer (viewer/amrviz_font.h).

    python3 tools/make_font_header.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf 15 > viewer/amrviz_font.h

Two atlases: amrviz_font at the given size, for ordinary displays, and
amrviz_font_2x at twice the size, for high-DPI (Retina) displays, where one
window unit is two pixels. Glyphs are stored as one row of cells, 8-bit
coverage: AMRVIZ_FONT_W x AMRVIZ_FONT_H pixels each in amrviz_font and
exactly twice that in amrviz_font_2x, with the baseline at the same place,
so text is laid out once in window units for both.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path, size = sys.argv[1], int(sys.argv[2])
chars = [chr(c) for c in range(32, 127)]

font1 = ImageFont.truetype(path, size)
asc1, desc1 = font1.getmetrics()
w1 = max(int(round(font1.getlength(c))) for c in chars)
h1 = asc1 + desc1


def atlas(scale):
    """the glyphs at scale * size in cells of scale * (w1, h1), baseline at scale * asc1"""
    font = ImageFont.truetype(path, scale * size)
    asc, _ = font.getmetrics()
    w, h = scale * w1, scale * h1
    img = Image.new("L", (w * len(chars), h), 0)
    d = ImageDraw.Draw(img)
    for k, c in enumerate(chars):
        d.text((k * w, scale * asc1 - asc), c, font=font, fill=255)
    return img.tobytes()


def print_array(name, px):
    print(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(px), 24):
        print("    " + ",".join(str(b) for b in px[i:i + 24]) + ",")
    print("};\n")


name = path.rsplit("/", 1)[-1]
print(f"/* Generated by tools/make_font_header.py from {name} at {size} and {2 * size} px.")
print(" * DejaVu changes are in the public domain; the Bitstream Vera glyphs are")
print(" * Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera")
print(" * is a trademark of Bitstream, Inc. (Bitstream Vera license, see")
print(" * https://dejavu-fonts.github.io/License.html) */")
print("#ifndef AMRVIZ_FONT_INCLUDED\n#define AMRVIZ_FONT_INCLUDED\n")
print(f"#define AMRVIZ_FONT_FIRST 32\n#define AMRVIZ_FONT_COUNT {len(chars)}")
print(f"#define AMRVIZ_FONT_W {w1}\n#define AMRVIZ_FONT_H {h1}\n")
print(f"/* {size} px, cells of AMRVIZ_FONT_W x AMRVIZ_FONT_H */")
print_array("amrviz_font", atlas(1))
print(f"/* {2 * size} px for high-DPI displays, cells of 2*AMRVIZ_FONT_W x 2*AMRVIZ_FONT_H */")
print_array("amrviz_font_2x", atlas(2))
print("#endif")
