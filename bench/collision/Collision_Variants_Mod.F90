    USE LBM_Common_Mod, ONLY: Perfect_Shift_AMR, Streaming_LaxWendroff_AMR
    USE, INTRINSIC :: ISO_C_BINDING, ONLY: C_INT, C_DOUBLE
    IMPLICIT NONE
    PUBLIC

    REAL(wp), PARAMETER, PRIVATE :: c13 = 1._wp/3._wp, c112 = 1._wp/12._wp, c23 = 2._wp/3._wp, c16 = 1._wp/6._wp

    !== block size as a run-time value (variant rt_size)
    INTEGER :: nx_rt = 0, ny_rt = 0
    !== the reference model (variants model, mc_model) and the current one (new, mc_new)
    TYPE(LBM_Model) :: the_model, new_model

    !== padded, cache-line aligned copy of the fields (variants al_*, see Al_Setup)
    INTEGER, PARAMETER :: ldp = nx + 8
    INTEGER, PARAMETER :: sz_h = ldp*(ny+2)*9, sz_C = ldp*(ny+4), sz_P = nx*ny
