    INTEGER :: o_h, o_g, o_C, o_P, o_Ux, o_Uy

    !== streaming variants (st_*): CFL number of a coarse level, stencil weights
    REAL(wp) :: st_cfl = 0.5_wp, st_w9(-1:1,-1:1,2:9), st_wx(-1:1,2:9), st_wy(-1:1,2:9)
    INTEGER  :: st_tensor = 0      ! weights in st_w9: 0 not set, 1 Lax-Wendroff along e_k, 2 tensor product

    !== the AVX-512 intrinsics kernels (collision_avx512.c), double precision
    REAL(wp) :: c512_par(11)
    INTERFACE
        INTEGER(C_INT) FUNCTION collision_avx512_available() BIND(C)
            IMPORT :: C_INT
        END FUNCTION collision_avx512_available
#define C512_IFACE(KN)         SUBROUTINE KN( inv_dx, par, C, P, Ux, Uy, h, g ) BIND(C);             IMPORT :: C_DOUBLE, nx, ny;             REAL(C_DOUBLE), INTENT(IN)    :: inv_dx, par(11), C(-1:nx+2,-1:ny+2);             REAL(C_DOUBLE), INTENT(INOUT) :: P(nx,ny), Ux(nx,ny), Uy(nx,ny);             REAL(C_DOUBLE), INTENT(INOUT) :: h(0:nx+1,0:ny+1,9), g(0:nx+1,0:ny+1,9);         END SUBROUTINE KN
        C512_IFACE( collision_jcp2016_avx512 )
        C512_IFACE( moments_collision_jcp2016_avx512 )
        C512_IFACE( collision_jcp2016_avx512_rcp )
        C512_IFACE( moments_collision_jcp2016_avx512_rcp )
        C512_IFACE( collision_jcp2016_avx512_nodiv )
        C512_IFACE( moments_collision_jcp2016_avx512_nodiv )
#undef C512_IFACE
    END INTERFACE

