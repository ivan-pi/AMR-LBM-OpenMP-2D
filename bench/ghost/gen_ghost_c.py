#!/usr/bin/env python3
"""Ghost_C_Variants.F90 (one module per variant from ghost_c_template.inc) and the driver's table."""
import json
variants = json.load(open('variants_c.json'))
with open('Ghost_C_Variants.F90', 'w') as f:
    f.write('!== generated by gen_ghost_c.py from variants_c.json: one module per variant of the ghost fill of C\n')
    for name, defs in variants:
        f.write('#define GC_MOD Ghost_C_v_%s\n' % name + ''.join('#define %s\n' % d for d in defs) + '#include "ghost_c_template.inc"\n\n')
names = ['src'] + [v[0] for v in variants] + ['fused_push']
with open('ghost_c_use.inc', 'w') as f:
    f.write('    USE Ghost_C_Mod, ONLY: Fill_src => Fill_Ghost_Cells_C\n')
    for name, _ in variants:
        f.write('    USE Ghost_C_v_%s, ONLY: Fill_%s => Fill_Ghost_Cells_C\n' % (name, name))
    f.write('    USE Ghost_C_v_push, ONLY: Push_C\n')
with open('ghost_c_table.inc', 'w') as f:
    f.write('    INTEGER, PARAMETER :: nVar = %d\n    TYPE(Variant_t) :: var(nVar)\n' % len(names))
with open('ghost_c_set.inc', 'w') as f:
    for k, n in enumerate(names, 1):
        if n == 'src':            # the module in src/ now, all copies in the fill
            f.write("    var(%d)%%name = 'src'\n    var(%d)%%run => Fill_src\n" % (k, k))
        elif n == 'fused_push':     # Push_C after C = sum(h) of each block, then the fill without the copies
            f.write("    var(%d)%%name = '%s'\n    var(%d)%%run => Fill_push\n    var(%d)%%post => Push_C\n" % (k, n, k, k))
        elif n == 'push':         # not fused: all pushes, then the fill, both timed as the fill
            f.write("    var(%d)%%name = '%s'\n    var(%d)%%run => Fill_push\n    var(%d)%%pre => Push_C\n" % (k, n, k, k))
        else:
            f.write("    var(%d)%%name = '%s'\n    var(%d)%%run => Fill_%s\n" % (k, n, k, n))
