#!/usr/bin/env python3
"""Ghost_Variants.F90 (one module per variant from ghost_template.inc) and the driver's table."""
import json
variants = json.load(open('variants.json'))
with open('Ghost_Variants.F90', 'w') as f:
    f.write('!== generated by gen_ghost.py from variants.json: one module per variant of the ghost fill\n')
    for name, defs in variants:
        f.write('#define GH_MOD Ghost_v_%s\n' % name + ''.join('#define %s\n' % d for d in defs) + '#include "ghost_template.inc"\n\n')
names = ['src'] + [v[0] for v in variants] + ['fused_push', 'fused_push_cfdirs']
# fused variants: Push_Block after the collision of each block, then a fill without the same-level copies
fused = {'fused_push': 'x_nocopy', 'fused_push_cfdirs': 'x_nocopy_cfdirs'}
with open('ghost_use.inc', 'w') as f:
    f.write('    USE Ghost_hg_Mod, ONLY: Fill_src => Fill_Ghost_Cells_hg, Push_src => Push_Same_Level\n')
    for name, _ in variants:
        f.write('    USE Ghost_v_%s, ONLY: Fill_%s => Fill_Ghost_Cells_hg\n' % (name, name))
    f.write('    USE Ghost_v_push, ONLY: Push_Block\n')
with open('ghost_table.inc', 'w') as f:
    f.write('    INTEGER, PARAMETER :: nVar = %d\n    TYPE(Variant_t) :: var(nVar)\n' % len(names))
with open('ghost_set.inc', 'w') as f:
    for k, n in enumerate(names, 1):
        if n == 'src':
            f.write("    var(%d)%%name = 'src'\n    var(%d)%%run => Fill_src\n    var(%d)%%post => Push_src\n" % (k, k, k))
        elif n in fused:
            f.write("    var(%d)%%name = '%s'\n    var(%d)%%run => Fill_%s\n    var(%d)%%post => Push_Block\n" % (k, n, k, fused[n], k))
        else:
            f.write("    var(%d)%%name = '%s'\n    var(%d)%%run => Fill_%s\n" % (k, n, k, n))
